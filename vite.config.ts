          id: '/',
          name: 'CRM - مصلحة الضرائب المصرية',
          short_name: 'CRM',
          description:
            'منظومة إدارة علاقات العملاء وخدمة الممولين لمركز الاتصال المتكامل بمصلحة الضرائب المصرية',
          theme_color: '#00264D',
          background_color: '#FFFFFF',
          display: 'standalone',
          orientation: 'portrait-primary',
          scope: '/',
          start_url: '/',
          dir: 'rtl',
          lang: 'ar',
